use super::*;

fn register(
    manager: &Manager,
    fixture: &crate::resource_package::repair::tests::Fixture,
    enabled: bool,
) -> ResourceRecord {
    let timestamp = now();
    let record = ResourceRecord {
        id: uuid::Uuid::new_v4().to_string(),
        name: "Generated npm repair fixture".into(),
        kind: "mcp".into(),
        root_path: display(&fixture.root),
        repository: Some("https://github.com/microsoft/playwright-mcp".into()),
        version: Some("0.0.83".into()),
        source_binding: None,
        source_history: vec![],
        alias: String::new(),
        notes: "Inert generated bytes only; no executable capability verified".into(),
        enabled,
        ownership: "managedFiles".into(),
        management_scope: "ownedFiles".into(),
        actions: vec![],
        capabilities: vec![json!({"id":"cliVersion","status":"unverified"})],
        update_policy: json!({"mode":"manual","intervalHours":24,"pinnedVersion":null,"skippedVersions":[]}),
        installation: Some(InstallationRecord {
            schema_version: 1,
            installed_at: timestamp.clone(),
            archive_path: String::new(),
            archive_sha256: String::new(),
            source_repository: Some("https://github.com/microsoft/playwright-mcp".into()),
            source_version: Some("0.0.83".into()),
            download_source: None,
            runtime_package: Some(fixture.provenance.clone()),
            files: fixture.owned.clone(),
            system_entries: vec![],
            status: "installed".into(),
            error: None,
            pending_repair: None,
            retained_repair_files: vec![],
            update_state: None,
            removal_state: None,
            resource_manifest: None,
        }),
        revision: 1,
        created_at: timestamp.clone(),
        updated_at: timestamp,
    };
    manager
        .resource_store(StoreRequest::Insert(Box::new(record.clone())))
        .unwrap();
    record
}
#[test]
fn npm_repair_uses_native_confirmation_and_keeps_original_source_policy_and_local_content() {
    for enabled in [false, true] {
        let fixture = crate::resource_package::repair::tests::fixture();
        let mut manager = Manager::new(fixture.root.parent().unwrap().join("state")).unwrap();
        let original = register(&manager, &fixture, enabled);
        let missing = "node_modules/@playwright/mcp/cli.js";
        fs::remove_file(fixture.root.join(missing)).unwrap();
        let modified = fixture.root.join("node_modules/playwright/index.js");
        fs::write(&modified, b"retained local customization").unwrap();
        let unknown = fixture.root.join("unknown-user-data");
        fs::write(&unknown, b"retained user material").unwrap();
        let request = json!({"action":"preview_resource_repair","id":original.id,"expectedRevision":original.revision});
        assert_eq!(repair_source_paths(&manager, &request).unwrap().len(), 3);
        let plan = handle(&mut manager, &request).unwrap().unwrap();
        assert_eq!(plan["canApply"], true);
        assert_eq!(plan["sourceFormat"], "npmTgz");
        assert!(plan["archivePath"].is_null());
        assert_eq!(plan["source"]["verification"], "npmIntegrity");
        assert_eq!(plan["sourcePaths"].as_array().unwrap().len(), 1);
        let apply = json!({"action":"apply_resource_repair","previewId":plan["id"]});
        assert!(crate::dispatch(&mut manager, &apply).is_err());
        let result = crate::dispatch_local(&mut manager, &apply).unwrap();
        assert_eq!(result["complete"], true);
        assert_eq!(result["ownershipSaved"], true);
        assert_eq!(result["resource"]["enabled"], enabled);
        assert!(result["receipt"]["failures"].as_array().unwrap().is_empty());
        assert_eq!(fs::read(modified).unwrap(), b"retained local customization");
        assert_eq!(fs::read(unknown).unwrap(), b"retained user material");
        let stored = read_resource(&manager, &original.id).unwrap();
        let installation = stored.installation.unwrap();
        assert!(installation.pending_repair.is_none());
        assert!(
            installation.archive_path.is_empty()
                && installation.archive_sha256.is_empty()
                && installation.download_source.is_none()
        );
        assert_eq!(
            serde_json::to_value(installation.runtime_package).unwrap(),
            serde_json::to_value(original.installation.unwrap().runtime_package).unwrap()
        );
        assert_eq!(stored.capabilities[0]["status"], "unverified");
        assert!(crate::dispatch_local(&mut manager, &apply).is_err());
    }
}
#[test]
fn npm_repair_source_drift_rejects_before_disabling_or_saving_a_new_intent() {
    let fixture = crate::resource_package::repair::tests::fixture();
    let mut manager = Manager::new(fixture.root.parent().unwrap().join("state")).unwrap();
    let original = register(&manager, &fixture, true);
    let missing = "node_modules/@playwright/mcp/cli.js";
    fs::remove_file(fixture.root.join(missing)).unwrap();
    let plan = handle(
        &mut manager,
        &json!({"action":"preview_resource_repair","id":original.id,"expectedRevision":1}),
    )
    .unwrap()
    .unwrap();
    let asset = plan["sourcePaths"][0].as_str().unwrap();
    fs::write(asset, b"not the original archive").unwrap();
    assert!(crate::dispatch_local(
        &mut manager,
        &json!({"action":"apply_resource_repair","previewId":plan["id"]})
    )
    .is_err());
    let stored = read_resource(&manager, &original.id).unwrap();
    assert_eq!(stored.revision, 1);
    assert!(stored.enabled && stored.installation.unwrap().pending_repair.is_none());
    assert!(!fixture.root.join(missing).exists());
    for path in plan["temporaryPaths"].as_array().unwrap() {
        assert!(!Path::new(path.as_str().unwrap()).exists());
    }
}
